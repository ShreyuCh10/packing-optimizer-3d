import os
from typing import Optional, List, Dict, Any
from fastapi import APIRouter, HTTPException, Query, Response
from app.db import get_unified_packaging, get_packaging_item_by_identifier
from app.services.mesh_service import generate_package_mesh

router = APIRouter(prefix="/packages", tags=["Packages"])


@router.get("", summary="List all packages (cartons, pallets, stillages) from SQLite")
def list_packages(
    category: Optional[str] = Query(default=None, description="Filter by packaging category: 'all', 'carton', 'base_pallet', 'metal_pallet', 'metal_stillage'"),
    search: Optional[str] = Query(default=None, description="Search by package name"),
    limit: Optional[int] = Query(default=None, ge=1, description="Limit results"),
    offset: int = Query(default=0, ge=0, description="Offset results"),
):
    """Retrieve packaging inventory units (excluding trucks) directly from SQLite database."""
    # Retrieve all packaging items
    all_packaging = get_unified_packaging(category="all")

    # Compute category counts for tab badges
    counts = {
        "all": len(all_packaging),
        "carton": len([p for p in all_packaging if p.get("category") == "carton"]),
        "base_pallet": len([p for p in all_packaging if p.get("category") == "base_pallet"]),
        "metal_pallet": len([p for p in all_packaging if p.get("category") == "metal_pallet"]),
        "metal_stillage": len([p for p in all_packaging if p.get("category") == "metal_stillage"]),
    }

    # Normalize parameters if called directly in tests
    cat_val = category.strip().lower() if isinstance(category, str) else None
    search_val = search.strip().lower() if isinstance(search, str) else None
    offset_val = offset if isinstance(offset, int) else 0
    limit_val = limit if isinstance(limit, int) else None

    # Filter by category if specified and not 'all'
    items = all_packaging
    if cat_val and cat_val != "all":
        items = [p for p in items if p.get("category") == cat_val]

    # Filter by search query
    if search_val:
        items = [
            p for p in items
            if search_val in str(p.get("package", "")).lower()
            or search_val in str(p.get("category_label", "")).lower()
        ]

    total = len(items)

    # Pagination
    if limit_val is not None:
        items = items[offset_val : offset_val + limit_val]
    elif offset_val > 0:
        items = items[offset_val:]

    return {
        "packages": items,
        "total": total,
        "counts": counts,
        "source": "sqlite",
    }


@router.get("/{package_identifier}", summary="Get a package by ID or name")
def get_package(package_identifier: str):
    """Retrieve a single package by numeric ID or package name."""
    item = get_packaging_item_by_identifier(package_identifier)
    if not item:
        raise HTTPException(
            status_code=404,
            detail=f"Package '{package_identifier}' not found in database.",
        )
    return item


@router.get("/{package_identifier}/mesh", summary="Get 3D mesh GLB for package rendering")
def get_package_mesh(package_identifier: str):
    """Serve a GLB 3D container mesh generated by Python's trimesh for WebGL/Three.js rendering."""
    item = get_packaging_item_by_identifier(package_identifier)
    if not item:
        raise HTTPException(
            status_code=404,
            detail=f"Package '{package_identifier}' not found in database.",
        )

    try:
        glb_bytes, filename = generate_package_mesh(item)
        headers = {
            "Content-Disposition": f'inline; filename="{filename}"',
            "X-Mesh-Source": "trimesh-procedural-package",
            "Access-Control-Expose-Headers": "X-Mesh-Source",
        }
        return Response(content=glb_bytes, media_type="model/gltf-binary", headers=headers)
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Failed to generate 3D mesh for package: {e}",
        )
